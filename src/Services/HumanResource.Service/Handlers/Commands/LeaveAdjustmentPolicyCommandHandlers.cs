using HumanResource.Service.Commands;
using HumanResource.Service.DTOs;
using HumanResource.Service.Entities;
using HumanResource.Service.Infrastructure.Data;
using MediatR;
using Microsoft.EntityFrameworkCore;

namespace HumanResource.Service.Handlers.Commands
{
    public sealed class LeaveAdjustmentPolicyCommandHandlers :
        IRequestHandler<CreateLeaveAdjustmentPolicyV3Command, LeaveAdjustmentPolicyV3Dto>,
        IRequestHandler<UpdateLeaveAdjustmentPolicyV3Command, bool>,
        IRequestHandler<DeleteLeaveAdjustmentPolicyV3Command, bool>
    {
        private readonly HumanResourceDbContext _context;

        public LeaveAdjustmentPolicyCommandHandlers(HumanResourceDbContext context)
        {
            _context = context;
        }

        public async Task<LeaveAdjustmentPolicyV3Dto> Handle(CreateLeaveAdjustmentPolicyV3Command command, CancellationToken cancellationToken)
        {
            var request = command.Request;

            // Generate Policy ID (code) if not provided, though it's usually generated by legacy logic
            // Legacy FE has it disabled/readonly, so it might be system generated in BE.
            // But let's follow the standard creation pattern.

            var nextId = (await _context.LeaveAdjustmentPolicies.IgnoreQueryFilters().MaxAsync(x => (int?)x.Id, cancellationToken) ?? 0) + 1;
            
            var header = new ETLeaveadjpolicyLegacy
            {
                Id = nextId,
                code = request.Code ?? $"LAP-{nextId}",
                stxt = request.Stxt?.Trim(),
                entityid = command.EntityId,
                clientid = command.ClientId,
                utblock = false
            };

            var detailNextId = (await _context.LeaveAdjustmentPolicyDetails.IgnoreQueryFilters().MaxAsync(x => (int?)x.Id, cancellationToken) ?? 0) + 1;

            foreach (var detailReq in request.Details)
            {
                header.Details.Add(new ETLeaveadjpolicydtlLegacy
                {
                    Id = detailNextId++,
                    leavetypeid = detailReq.LeaveTypeId,
                    adjtypeid = detailReq.AdjTypeId,
                    basedonid = detailReq.BasedOnId,
                    priorityid = detailReq.PriorityId,
                    days = detailReq.Days,
                    utblock = false
                });
            }

            _context.LeaveAdjustmentPolicies.Add(header);
            await _context.SaveChangesAsync(cancellationToken);

            // Fetch names for the response
            var leaveTypes = await _context.LeaveTypes
                .Select(x => new { x.Id, x.stxt })
                .ToDictionaryAsync(x => x.Id, x => x.stxt, cancellationToken);
            var lovs = await _context.Lovs
                .Where(x => x.Vtype == "ADJP" || x.Vtype == "PRIT")
                .Select(x => new { x.Id, x.Stxt })
                .ToDictionaryAsync(x => x.Id, x => x.Stxt, cancellationToken);
            var atnPolicies = await _context.AttendancePolicies
                .Select(x => new { x.Id, x.Stxt })
                .ToDictionaryAsync(x => x.Id, x => x.Stxt, cancellationToken);

            return new LeaveAdjustmentPolicyV3Dto
            {
                Id = header.Id,
                Code = header.code,
                Stxt = header.stxt,
                Details = header.Details.Select(d => new LeaveAdjustmentPolicyDetailV3Dto
                {
                    Id = d.Id,
                    LeaveTypeId = d.leavetypeid,
                    LeaveTypeName = d.leavetypeid.HasValue && leaveTypes.ContainsKey(d.leavetypeid.Value)
                        ? leaveTypes[d.leavetypeid.Value]
                        : null,
                    AdjTypeId = d.adjtypeid,
                    AdjTypeName = d.adjtypeid.HasValue && lovs.ContainsKey(d.adjtypeid.Value)
                        ? lovs[d.adjtypeid.Value]
                        : null,
                    BasedOnId = d.basedonid,
                    BasedOnName = d.basedonid.HasValue && atnPolicies.ContainsKey(d.basedonid.Value)
                        ? atnPolicies[d.basedonid.Value]
                        : null,
                    PriorityId = d.priorityid,
                    PriorityName = d.priorityid.HasValue && lovs.ContainsKey(d.priorityid.Value)
                        ? lovs[d.priorityid.Value]
                        : null,
                    Days = d.days
                }).ToList()
            };
        }

        public async Task<bool> Handle(UpdateLeaveAdjustmentPolicyV3Command command, CancellationToken cancellationToken)
        {
            var request = command.Request;
            var header = await _context.LeaveAdjustmentPolicies
                .Include(x => x.Details)
                .FirstOrDefaultAsync(x => x.Id == request.Id && x.clientid == command.ClientId, cancellationToken);

            if (header == null) return false;

            header.stxt = request.Stxt?.Trim();
            header.code = request.Code?.Trim();

            // Update Details
            var detailNextId = (await _context.LeaveAdjustmentPolicyDetails.IgnoreQueryFilters().MaxAsync(x => (int?)x.Id, cancellationToken) ?? 0) + 1;

            foreach (var detailReq in request.Details)
            {
                if (detailReq.Id.HasValue && detailReq.Id.Value > 0)
                {
                    var existingDetail = header.Details.FirstOrDefault(d => d.Id == detailReq.Id.Value);
                    if (existingDetail != null)
                    {
                        if (detailReq.Delete)
                        {
                            _context.LeaveAdjustmentPolicyDetails.Remove(existingDetail);
                        }
                        else
                        {
                            existingDetail.leavetypeid = detailReq.LeaveTypeId;
                            existingDetail.adjtypeid = detailReq.AdjTypeId;
                            existingDetail.basedonid = detailReq.BasedOnId;
                            existingDetail.priorityid = detailReq.PriorityId;
                            existingDetail.days = detailReq.Days;
                        }
                    }
                }
                else if (!detailReq.Delete)
                {
                    // Add new detail
                    header.Details.Add(new ETLeaveadjpolicydtlLegacy
                    {
                        Id = detailNextId++,
                        leavetypeid = detailReq.LeaveTypeId,
                        adjtypeid = detailReq.AdjTypeId,
                        basedonid = detailReq.BasedOnId,
                        priorityid = detailReq.PriorityId,
                        days = detailReq.Days,
                        utblock = false
                    });
                }
            }

            await _context.SaveChangesAsync(cancellationToken);
            return true;
        }

        public async Task<bool> Handle(DeleteLeaveAdjustmentPolicyV3Command command, CancellationToken cancellationToken)
        {
            var header = await _context.LeaveAdjustmentPolicies
                .FirstOrDefaultAsync(x => x.Id == command.Id && x.clientid == command.ClientId, cancellationToken);

            if (header == null) return false;

            if (await _context.LeaveGroups.AnyAsync(x => x.AdjustmentPolicyId == header.Id, cancellationToken))
                throw new InvalidOperationException("Cannot delete Leave Adjustment Policy because it is used in a Leave Group.");

            var details = await _context.LeaveAdjustmentPolicyDetails
                .Where(x => x.leaveadjid == header.Id)
                .ToListAsync(cancellationToken);

            _context.LeaveAdjustmentPolicyDetails.RemoveRange(details);
            _context.LeaveAdjustmentPolicies.Remove(header);
            await _context.SaveChangesAsync(cancellationToken);
            return true;
        }
    }
}
